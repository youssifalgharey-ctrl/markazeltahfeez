def clean_gemini_text(text: str) -> str:
    """تنظيف وتنسيق النص المستخرج من Gemini."""
    if not text:
        return ""
    # إزالة أي صيغ غريبة للـ JSON إذا ظهرت بالخطأ
    text = text.strip()
    return text

