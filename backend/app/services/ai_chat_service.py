def clean_gemini_text(text: str) -> str:
    """تنظيف وتنسيق النص المستخرج من Gemini."""
    if not text:
        return ""
    return text.strip()

async def call_gemini_chat(request: AIChatRequest, user_name: Optional[str] = None) -> AIChatResponse:
    """إرسال المحادثة إلى Gemini مع الاستناد لقاعدة المعرفة إذا تعذر الاتصال."""
    # التحقق من وجود مفتاح
    api_key = settings.GEMINI_API_KEY.strip() if settings.GEMINI_API_KEY else ""
    if not api_key or "ضع_هنا" in api_key:
        logger.info("Using internal comprehensive knowledge base engine.")
        return find_fallback_response(request.message)

    url = f"https://generativelanguage.googleapis.com/v1beta/models/{settings.GEMINI_MODEL}:generateContent?key={api_key}"

    user_greeting_ctx = f"اسم الطالب الذي يخاطبك الآن: {user_name}.\n" if user_name else ""
    system_instruction = SYSTEM_PROMPT + "\n" + user_greeting_ctx

    contents = []
    if request.history:
        for msg in request.history[-6:]:
            role = "user" if msg.role == "user" else "model"
            contents.append({
                "role": role,
                "parts": [{"text": msg.content}]
            })

    contents.append({
        "role": "user",
        "parts": [{"text": request.message}]
    })

    payload = {
        "systemInstruction": {
            "parts": [{"text": system_instruction}]
        },
        "contents": contents,
        "generationConfig": {
            "temperature": 0.5,
            "maxOutputTokens": 1000,
        }
    }

    try:
        async with httpx.AsyncClient(timeout=25.0) as client:
            response = await client.post(url, json=payload)
            if response.status_code != 200:
                logger.warning("Gemini API returned status %s. Falling back to local engine.", response.status_code)
                return find_fallback_response(request.message)

            data = response.json()
            candidates = data.get("candidates", [])
            if not candidates:
                return find_fallback_response(request.message)

            reply_text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
            if not reply_text:
                return find_fallback_response(request.message)

            cleaned_reply = clean_gemini_text(reply_text)
            suggestions = extract_dynamic_suggestions(cleaned_reply)

            return AIChatResponse(
                reply=cleaned_reply,
                suggestions=suggestions,
                source="gemini"
            )
    except Exception as e:
        logger.error("Error communicating with Gemini API: %s. Using fallback engine.", e)
        return find_fallback_response(request.message)

def extract_dynamic_suggestions(reply: str) -> List[str]:
    """توليد 2-3 أسئلة متابعة مقترحة مناسبة لمحتوى الرد."""
    norm = normalize_arabic(reply)
    suggestions = []
    
    if "نتيجه" in norm or "درج" in norm:
        suggestions.append("كيف أختبر نفسي في إختبرني؟")
        suggestions.append("ما هي محتويات القائمة الجانبية؟")
    elif "قائم" in norm or "منيو" in norm:
        suggestions.append("كيف أصل لخانة نتيجتي؟")
        suggestions.append("كيف أعدل بيانات ملفي الشخصي؟")
    elif "تجويد" in norm or "تسميع" in norm:
        suggestions.append("كيف أحجز جلسة تسميع مع الشيخ؟")
        suggestions.append("كيف أحصل على إجازة بالسند؟")
    elif "اشتراك" in norm or "دفع" in norm or "كاش" in norm:
        suggestions.append("كيف أعرف أن اشتراكي تفعل؟")
        suggestions.append("ما هي المسارات المتاحة بالمنصة؟")
    elif "مبتدئ" in norm or "اطفال" in norm:
        suggestions.append("كيف أصمم خطة حفظ تناسب وقتي؟")
        suggestions.append("ما هي شروط مسار الإجازة؟")
    
    for item in DEFAULT_SUGGESTIONS:
        if len(suggestions) >= 3:
            break
        if item not in suggestions:
            suggestions.append(item)
            
    return suggestions[:3]
