# محرك المطابقة الدلالية الذكي (Local NLP & Intent Matcher)
# =====================================================================
def find_fallback_response(message: str) -> AIChatResponse:
    """محرك مطابقة ذكي يفهم العامية المصرية، ويبحث بأوزان دلالية دقيقة."""
    norm_msg = normalize_arabic(message)
    tokens = norm_msg.split()
    
    best_item = None
    max_score = 0

    # كلمات دلالية خاصة ترفع الأولوية
    is_asking_result = any(k in norm_msg for k in ["نتيج", "درج", "شهاده", "result"])
    is_asking_sidemenu = any(k in norm_msg for k in ["سايد", "side", "قائم", "منيو", "menu"])
    
    # فحص خاص إذا جمع المستخدم بين نتيجتي والقائمة الجانبية معاً
    if is_asking_result and is_asking_sidemenu:
        # هذه الحالة المحددة التي اشتكى منها المستخدم:
        # "ازاي اجيب النتيجه اللي الخانه بتاعت نتيجتي في ال side menu"
        for item in COMPREHENSIVE_KNOWLEDGE:
            if item["id"] == "result_lookup":
                return AIChatResponse(
                    reply=item["reply"],
                    suggestions=item.get("suggestions", DEFAULT_SUGGESTIONS[:3]),
                    source="knowledge_base"
                )

    for item in COMPREHENSIVE_KNOWLEDGE:
        score = 0
        for kw in item["keywords"]:
            norm_kw = normalize_arabic(kw)
            
            # تطابق كامل مع العبارة
            if norm_kw == norm_msg:
                score += 50
            # وجود العبارة كاملة كجزء من الرسالة
            elif norm_kw in norm_msg:
                # الكلمات الأطول والأدق لها وزن أكبر
                score += 15 + len(norm_kw.split()) * 5
            else:
                # تطابق الكلمات الفردية
                kw_tokens = norm_kw.split()
                matches = sum(1 for t in kw_tokens if t in tokens)
                if matches > 0 and matches == len(kw_tokens):
                    score += 10 * matches
                elif matches > 0:
                    score += 3 * matches

        if score > max_score:
            max_score = score
            best_item = item

    if best_item and max_score >= 10:
        return AIChatResponse(
            reply=best_item["reply"],
            suggestions=best_item.get("suggestions", DEFAULT_SUGGESTIONS[:3]),
            source="knowledge_base"
        )

    # رد افتراضي غني ومباشر إذا لم تكن النية واضحة
    general_reply = (
        "مرحباً بك في **مركز تحفيظ القرآن الكريم بأسريجه**! 🌸\n\n"
        "أنا مرشدك الذكي، ومستعد لمساعدتك في كل ما يخص المنصة:\n\n"
        "• **لمعرفة درجاتك وشهاداتك**: اضغط على زر القائمة (☰) أعلى الصفحة واختر **[نتيجتي](/result.html)**.\n"
        "• **لتصفح الكورسات والمسارات**: تفضل بزيارة صفحة **[الكورسات](/courses.html)**.\n"
        "• **لحجز جلسة تسميع وتصحيح تلاوة مباشرة مع شيخ مجاز**: ادخل على **[حجز جلسة تجويد](/tajweed-booking.html)**.\n"
        "• **لتصميم خطة حفظ بالذكاء الاصطناعي**: استخدم البطاقة التفاعلية في **[الرئيسية](/home.html)**.\n"
        "• **لإجراء الاختبارات الإلكترونية**: توجه لصفحة **[إختبرني](/quiz.html)**.\n\n"
        "يمكنك سؤالي بأي طريقة (بالعامية أو الفصحى)، مثل:\n"
        "«ازاي اجيب نتيجتي»، «عايز اسمع للشيخ»، «طرق الدفع والاشتراك»، «ازاي افتح القائمة الجانبية»."
    )
    return AIChatResponse(
        reply=general_reply,
        suggestions=DEFAULT_SUGGESTIONS[:4],
        source="knowledge_base"
    )

