async def call_gemini_chat(request: AIChatRequest, user_name: Optional[str] = None) -> AIChatResponse:
    """إرسال المحادثة إلى Gemini 2.0 Flash وتوليد رد تفاعلي دقيق."""
    if not settings.GEMINI_API_KEY or "ضع_هنا" in settings.GEMINI_API_KEY:
        logger.info("No valid GEMINI_API_KEY found, using local knowledge base.")
        return find_fallback_response(request.message)

    url = f"https://generativelanguage.googleapis.com/v1beta/models/{settings.GEMINI_MODEL}:generateContent?key={settings.GEMINI_API_KEY}"

    # صياغة السياق والمحادثة
    contents = []

    # تخصيص التحية إذا كان اسم المستخدم معروفاً
    user_greeting_ctx = f"اسم الطالب الذي يخاطبك الآن: {user_name}.\n" if user_name else ""

    system_instruction = SYSTEM_PROMPT + "\n" + user_greeting_ctx

    # تجميع التاريخ السابق (بحد أقصى آخر 6 رسائل لتوفير التوكنز والحفاظ على السرعة)
    if request.history:
        for msg in request.history[-6:]:
            role = "user" if msg.role == "user" else "model"
            contents.append({
                "role": role,
                "parts": [{"text": msg.content}]
            })

    # إضافة الرسالة الحالية
    contents.append({
        "role": "user",
        "parts": [{"text": request.message}]
    })

    payload = {
        "systemInstruction": {
            "parts": [{"text": system_instruction}]
        },
        "contents": contents,
        "generationConfig": {
            "temperature": 0.6,
            "maxOutputTokens": 1000,
        }
    }

    try:
        async with httpx.AsyncClient(timeout=20.0) as client:
            response = await client.post(url, json=payload)
            if response.status_code != 200:
                logger.warning("Gemini API returned status %s: %s", response.status_code, response.text)
                return find_fallback_response(request.message)

            data = response.json()
            candidates = data.get("candidates", [])
            if not candidates:
                return find_fallback_response(request.message)

            reply_text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
            if not reply_text:
                return find_fallback_response(request.message)

            cleaned_reply = clean_gemini_text(reply_text)

            # تحديد مقترحات سياقية ذكية للرد
            suggestions = extract_dynamic_suggestions(cleaned_reply)

            return AIChatResponse(
                reply=cleaned_reply,
                suggestions=suggestions,
                source="gemini"
            )
    except Exception as e:
        logger.error("Error communicating with Gemini API: %s", e)
        return find_fallback_response(request.message)

def extract_dynamic_suggestions(reply: str) -> List[str]:
    """توليد 2-3 أسئلة متابعة مقترحة مناسبة لمحتوى الرد."""
    suggestions = []
    if "تجويد" in reply and "إجازة" not in reply:
        suggestions.append("كيف أحصل على إجازة قرآنية؟")
    if "إجازة" in reply:
        suggestions.append("ما هي شروط التقدم للاختبار؟")
    if "خطة" in reply:
        suggestions.append("كيف أبدأ تصميم خطتي الآن؟")
    if "اشتراك" in reply or "دفع" in reply:
        suggestions.append("ما هي وسائل الدفع المتاحة؟")
    if "مبتدئ" in reply:
        suggestions.append("ما هي أول سورة أبدأ بحفظها؟")
    
    # تكميل المقترحات بمقترحات عامة إذا كانت قليلة
    for item in DEFAULT_SUGGESTIONS:
        if len(suggestions) >= 3:
            break
        if item not in suggestions:
            suggestions.append(item)
            
    return suggestions[:3]
