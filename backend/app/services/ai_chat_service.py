def normalize_arabic(text: str) -> str:
    """تطبيع النص العربي وإزالة التشكيل والزوائد لضمان مطابقة ذكية ودقيقة."""
    if not text:
        return ""
    
    # تحويل للحروف الصغيرة (للكلمات الإنجليزية مثل side menu)
    text = text.lower()
    
    # إزالة التشكيل والتطويل
    text = re.sub(r'[\u064B-\u065F\u0670\u0640]', '', text)
    
    # توحيد الألفات
    text = re.sub(r'[أإآٱ]', 'ا', text)
    
    # توحيد الياء والألف المقصورة
    text = re.sub(r'[ى]', 'ي', text)
    
    # توحيد التاء المربوطة والهاء في أواخر الكلمات
    text = re.sub(r'ة\b', 'ه', text)
    
    # إزالة الرموز الخاصة مع الإبقاء على الحروف والأرقام
    text = re.sub(r'[^\w\s]', ' ', text)
    
    # دمج المسافات
    text = re.sub(r'\s+', ' ', text).strip()
    return text

